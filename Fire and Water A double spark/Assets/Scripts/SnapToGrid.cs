using UnityEngine;

/// <summary>
/// Повесьте этот компонент на квадратный (кубический) префаб.
/// cellSize — размер стороны префаба в юнитах (одинаковый по X/Y/Z),
/// чтобы объекты стыковались вплотную со всех сторон: слева, справа,
/// спереди, сзади, сверху и снизу.
/// </summary>
public class SnapToGrid : MonoBehaviour
{
    [Tooltip("Размер стороны кубического префаба в юнитах. Должен совпадать у всех префабов, которые должны стыковаться.")]
    public float cellSize = 1f;

    [Tooltip("Смещение сетки, если начало координат сцены не совпадает с углом карты.")]
    public Vector3 gridOffset = Vector3.zero;
}